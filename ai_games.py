def bank(kind: str) -> list:
    """Список вопросов игры: [{"id", "q", "opts", "a", "why"}], варианты уже перемешаны."""
    out = []
    if kind == "tool":
        for i, (task, right, wrong, why) in enumerate(TOOLS):
            out.append(_mk(f"t{i}", f"🧰 Какой инструмент подойдёт?\n\n<b>{task}</b>", [right] + wrong, why))
    elif kind == "prompt":
        for i, (sit, opts, a, why) in enumerate(PROMPTS):
            labels = "ABC"
            body = "\n\n".join(f"<b>{labels[k]}</b>: <i>{_esc(p)}</i>" for k, p in enumerate(opts))
            out.append({"id": f"p{i}", "q": f"✍️ Задача: <b>{sit}</b>\nКакой промпт лучше?\n\n{body}",
                        "opts": [labels[k] for k in range(len(opts))], "a": a, "why": why, "fixed": True})
    elif kind == "term":
        meanings = [m for _, m in TERMS]
        for i, (term, meaning) in enumerate(TERMS):
            wrong = random.sample([m for m in meanings if m != meaning], 2)
            out.append(_mk(f"w{i}", f"📚 Что значит <b>{term}</b>?", [meaning] + wrong, f"{term} — {meaning.lower()}."))
    elif kind == "myth":
        for i, (st, truth, why) in enumerate(MYTHS):
            out.append({"id": f"m{i}", "q": f"✅ Правда или миф?\n\n<b>{st}</b>", "opts": ["✅ Правда", "❌ Миф"],
                        "a": 0 if truth else 1, "why": why, "fixed": True})
    return out


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _mk(qid, q, opts, why):
    """Перемешивает варианты; правильный — первый в исходном списке."""
    right = opts[0]
    opts = opts[:]
    random.shuffle(opts)
    return {"id": qid, "q": q, "opts": opts, "a": opts.index(right), "why": why}


def pick(kind: str, seen: set, n: int) -> list:
    """n вопросов без повторов: сначала невиданные; когда всё пройдено — круг заново."""
    qs = bank(kind)
    fresh = [q for q in qs if q["id"] not in seen]
    random.shuffle(fresh)
    if len(fresh) >= n:
        return fresh[:n]
    rest = [q for q in qs if q["id"] in seen]
    random.shuffle(rest)
    return fresh + rest[:n - len(fresh)]


def total(kind: str) -> int:
    return {"tool": len(TOOLS), "prompt": len(PROMPTS), "term": len(TERMS), "myth": len(MYTHS)}[kind]
