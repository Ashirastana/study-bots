"""Очки и уровни для языковых ботов (испанский, турецкий).

Единая система мотивации: ученик получает очки за проверку слов, просмотр
видео и выполненные задания; с ростом очков открываются уровни. Логика
одинаковая для обоих ботов, поэтому вынесена сюда и импортируется и в
studybot.py (ES), и в turkbot.py (TR). Хранение самих очков — в таблице
students (колонка xp), методы db.add_xp / db.get_xp.
"""

# Пороги подобраны так, чтобы уровень рос примерно раз в 1–2 недели занятий.
LEVELS = [
    (0,    "🌱 Новичок"),
    (50,   "🙂 Уверенный старт"),
    (150,  "📗 Почти A1"),
    (350,  "📘 Крепкий A1"),
    (700,  "📙 Выхожу на A2"),
    (1200, "🏆 Уверенный A2+"),
]

# Сколько очков за что (единые правила для обоих ботов).
XP_PER_CORRECT = 1    # за каждый верный ответ в проверке слов
XP_QUIZ_PERFECT = 3   # бонус за проверку без ошибок
XP_DAILY_DONE = 3     # «Сегодня всё сделал(а)» — один раз в день
XP_VIDEO = 5          # посмотрел(а) видео — один раз в день
XP_REVIEW_MISTAKE = 1  # за верный повтор ранее ошибочного слова/фразы


def level(xp: int):
    """Возвращает (название текущего уровня, порог следующего уровня или None)."""
    name, nxt = LEVELS[0][1], None
    for i, (need, nm) in enumerate(LEVELS):
        if xp >= need:
            name = nm
            nxt = LEVELS[i + 1][0] if i + 1 < len(LEVELS) else None
    return name, nxt


def line(xp: int) -> str:
    """Готовая строка для экрана «Мои успехи»."""
    name, nxt = level(xp)
    tail = f" (до следующего — {nxt - xp})" if nxt else " — максимум! 🎉"
    return f"⭐ Очки: <b>{xp}</b> · {name}{tail}"
