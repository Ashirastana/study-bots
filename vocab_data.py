FIRST = ["hola", "adiós", "gracias", "por favor", "sí", "no", "me llamo …", "¿cómo estás?", "bien", "mal",
         "mucho gusto", "de nada", "perdón", "buenos días", "buenas noches", "hasta luego", "no entiendo",
         "¿cómo se dice …?", "más despacio, por favor", "yo", "tú", "usted", "él / ella", "y", "pero",
         "muy", "agua", "café", "casa", "familia", "amigo / amiga", "uno", "dos", "tres", "cuatro", "cinco",
         "seis", "siete", "ocho", "nueve", "diez"]


def load():
    seen, out = set(), []
    for line in (EXTRA + "\n" + RAW).splitlines():
        parts = [p.strip() for p in line.split("|")]
        if len(parts) != 3 or parts[0] in seen:
            continue
        seen.add(parts[0])
        out.append(tuple(parts))
    first = [w for f in FIRST for w in out if w[0] == f]
    rest = [w for w in out if w[0] not in FIRST]
    return first + rest


WORDS = load()
