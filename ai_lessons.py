TOTAL = len(LESSONS)


def lesson(n: int) -> dict | None:
    return LESSONS[n] if 0 <= n < TOTAL else None


def block_name(n: int) -> str:
    return BLOCKS[LESSONS[n]["block"]]


def short(n: int) -> str:
    return f"Урок {n + 1}. {LESSONS[n]['title']}"


def block_starts() -> list:
    """[(код блока, первый урок блока)] по порядку появления."""
    seen, out = set(), []
    for i, L in enumerate(LESSONS):
        if L["block"] not in seen:
            seen.add(L["block"])
            out.append((L["block"], i))
    return out
