def lesson_for_day(day_index: int):
    """День 0,1 — урок 1; день 2,3 — урок 2 … (номер урока, урок, день урока 1/2)."""
    n = day_index // 2
    if n < len(LESSONS):
        return n + 1, LESSONS[n], day_index % 2 + 1
    # после программы — повторяем уроки по кругу
    k = (n - len(LESSONS)) % len(LESSONS)
    return k + 1, LESSONS[k], 2


def lesson_text(day_index: int) -> str:
    num, (title, expl, examples, kk, task), part = lesson_for_day(day_index)
    head = f"📖 <b>Урок {num}: {title}</b>" + (" — закрепляем" if part == 2 else "")
    ex = "\n".join(f"• {e}" for e in examples)
    out = [head, "", expl, "", "<b>Примеры:</b>", ex]
    if kk:
        out += ["", f"🇰🇿 {kk}"]
    out += ["", f"✍️ <b>Задание:</b> {task}",
            "Ответьте учителю — нажмите «🗣 Поговорить с учителем» и выполните задание текстом или голосом."]
    return "\n".join(out)


def lesson_topic(day_index: int) -> str:
    num, (title, expl, *_), part = lesson_for_day(day_index)
    return f"Урок {num}: {title}. {expl}"
